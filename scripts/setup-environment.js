#!/usr/bin/env node

/**
 * Environment Setup Script
 * Interactive setup for environment variables
 */

const fs = require('fs');
const path = require('path');
const readline = require('readline');

const ENV_FILE = path.join(__dirname, '..', '.env');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

function question(prompt) {
  return new Promise((resolve) => {
    rl.question(prompt, resolve);
  });
}

function generateJWTSecret() {
  return require('crypto').randomBytes(32).toString('base64');
}

async function setupEnvironment() {
  console.log('🚀 Cadillac Dealership System - Environment Setup\n');
  console.log('This script will help you configure your environment variables.\n');

  // Check if .env already exists
  if (fs.existsSync(ENV_FILE)) {
    const overwrite = await question('⚠️  .env file already exists. Overwrite? (y/N): ');
    if (overwrite.toLowerCase() !== 'y' && overwrite.toLowerCase() !== 'yes') {
      console.log('Setup cancelled.');
      rl.close();
      return;
    }
  }

  console.log('📝 Gathering configuration...\n');

  // Supabase Configuration
  console.log('🔧 SUPABASE DATABASE SETUP');
  console.log('   Create a project at: https://supabase.com\n');

  const supabaseUrl = await question('   Supabase Project URL: ');
  const supabaseAnonKey = await question('   Supabase Anon Key: ');
  const supabaseServiceKey = await question('   Supabase Service Role Key (keep secret!): ');

  // Turso Configuration (optional)
  console.log('\n🔧 TURSO DATABASE SETUP (Optional - for hybrid architecture)');
  console.log('   Create a database at: https://turso.tech\n');

  const setupTurso = await question('   Set up Turso database? (y/N): ');
  let tursoUrl = '';
  let tursoToken = '';

  if (setupTurso.toLowerCase() === 'y' || setupTurso.toLowerCase() === 'yes') {
    tursoUrl = await question('   Turso Database URL: ');
    tursoToken = await question('   Turso Auth Token: ');
  }

  // Email Configuration (optional)
  console.log('\n📧 EMAIL CONFIGURATION (Optional)');
  const setupEmail = await question('   Set up email notifications? (y/N): ');

  let smtpHost = 'smtp.gmail.com';
  let smtpPort = '587';
  let smtpUser = '';
  let smtpPass = '';

  if (setupEmail.toLowerCase() === 'y' || setupEmail.toLowerCase() === 'yes') {
    smtpHost = await question(`   SMTP Host [${smtpHost}]: `) || smtpHost;
    smtpPort = await question(`   SMTP Port [${smtpPort}]: `) || smtpPort;
    smtpUser = await question('   SMTP Username (email): ');
    smtpPass = await question('   SMTP Password/App Password: ');
  }

  // CRM Configuration (optional)
  console.log('\n🔗 CRM INTEGRATION (Optional)');
  const setupCRM = await question('   Set up CRM integration? (y/N): ');

  let crmApiKey = '';
  let crmBaseUrl = '';

  if (setupCRM.toLowerCase() === 'y' || setupCRM.toLowerCase() === 'yes') {
    crmBaseUrl = await question('   CRM API Base URL: ');
    crmApiKey = await question('   CRM API Key: ');
  }

  // Task Master API Keys (optional)
  console.log('\n🤖 TASK MASTER AI ASSISTANCE (Optional)');
  console.log('   Get API keys from respective providers:\n');
  console.log('   - Anthropic (Claude): https://console.anthropic.com/');
  console.log('   - Perplexity: https://www.perplexity.ai/settings/api');
  console.log('   - OpenAI: https://platform.openai.com/api-keys');
  console.log('   - Google AI: https://makersuite.google.com/app/apikey\n');

  const anthropicKey = await question('   Anthropic API Key (optional): ');
  const perplexityKey = await question('   Perplexity API Key (optional): ');
  const openaiKey = await question('   OpenAI API Key (optional): ');
  const googleKey = await question('   Google AI API Key (optional): ');

  // Generate JWT secret
  const jwtSecret = generateJWTSecret();
  console.log('\n🔐 Generated secure JWT secret for authentication');

  // Create .env content
  const envContent = `# ============================================
# ENVIRONMENT CONFIGURATION FOR CADILLAC DEALERSHIP SYSTEM
# ============================================
# Generated by setup-environment.js on ${new Date().toISOString()}

# Task Master API Keys (for AI-assisted development)
ANTHROPIC_API_KEY="${anthropicKey || ''}"
PERPLEXITY_API_KEY="${perplexityKey || ''}"
OPENAI_API_KEY="${openaiKey || ''}"
GOOGLE_API_KEY="${googleKey || ''}"

# ============================================
# AUTHENTICATION & SECURITY
# ============================================

# JWT Configuration (REQUIRED for sales authentication)
JWT_SECRET=${jwtSecret}
JWT_EXPIRES_IN=8h

# ============================================
# DATABASE CONFIGURATION
# ============================================

# Supabase Database (PRIMARY - for complex operations)
SUPABASE_URL=${supabaseUrl}
SUPABASE_ANON_KEY=${supabaseAnonKey}
SUPABASE_SERVICE_ROLE_KEY=${supabaseServiceKey}

# Turso Database (SECONDARY - for fast reads and edge operations)
TURSO_DATABASE_URL=${tursoUrl}
TURSO_AUTH_TOKEN=${tursoToken}

# ============================================
# EMAIL & COMMUNICATIONS
# ============================================

# SMTP Configuration (for lead notifications and follow-ups)
SMTP_HOST=${smtpHost}
SMTP_PORT=${smtpPort}
SMTP_USER=${smtpUser}
SMTP_PASS=${smtpPass}

# ============================================
# EXTERNAL INTEGRATIONS
# ============================================

# CRM Integration (for lead syncing)
CRM_API_KEY=${crmApiKey}
CRM_BASE_URL=${crmBaseUrl}

# Inventory API (Cadillac dealership website)
INVENTORY_API_ENDPOINT=https://www.cadillacofsouthcharlotte.com/apis/widget/INVENTORY_LISTING_DEFAULT_AUTO_ALL:inventory-data-bus1/getInventory

# ============================================
# DEVELOPMENT SETTINGS
# ============================================

# Node Environment
NODE_ENV=development

# Hugo Build Settings
HUGO_ENV=development
`;

  // Write .env file
  fs.writeFileSync(ENV_FILE, envContent);

  console.log('\n✅ Environment configuration saved to .env');
  console.log('\n📋 NEXT STEPS:');
  console.log('1. Review the generated .env file');
  console.log('2. Run database migrations: npm run migrate');
  console.log('3. Start development: npm run dev');
  console.log('\n🔒 IMPORTANT: Keep your .env file secure and never commit it to version control!');

  rl.close();
}

// Handle errors
process.on('uncaughtException', (error) => {
  console.error('❌ Setup failed:', error.message);
  rl.close();
  process.exit(1);
});

process.on('unhandledRejection', (error) => {
  console.error('❌ Setup failed:', error.message);
  rl.close();
  process.exit(1);
});

// Run setup
setupEnvironment();